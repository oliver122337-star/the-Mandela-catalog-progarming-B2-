n1=input("first number:")
n2=input("second number:")
sign=input("sign:")

n1=int(n1)
n2=int(n2)

if sign=="+":
    print(n1,"+",n2,"=",n1+n2)
elif sign=="-":

        print(n1,"-",n2,"=",n1-n2)

elif sign=="*":
        print(n1,"*",n2,"=",n1*n2)

elif sign=="/":
        print(n1,"/",n2,"=",n1/n2)






